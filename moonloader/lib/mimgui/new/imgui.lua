local function this_dir()
    local src = debug.getinfo(1, 'S').source
    if src:sub(1, 1) == '@' then src = src:sub(2) end
    local dir = src:match('^(.*[/\\])')
    if dir then return dir end
    return getWorkingDirectory() .. [[\lib\mimgui\]]
end
