local function _remap_corner_flags(flags)
    if flags == nil or flags == 0 then return 0 end
    if bit.band(flags, 0x1F0) ~= 0 then return flags end
    local out = 0
    if bit.band(flags, 1) ~= 0 then out = bit.bor(out, lib.ImDrawFlags_RoundCornersTopLeft or 16) end
    if bit.band(flags, 2) ~= 0 then out = bit.bor(out, lib.ImDrawFlags_RoundCornersTopRight or 32) end
    if bit.band(flags, 4) ~= 0 then out = bit.bor(out, lib.ImDrawFlags_RoundCornersBottomLeft or 64) end
    if bit.band(flags, 8) ~= 0 then out = bit.bor(out, lib.ImDrawFlags_RoundCornersBottomRight or 128) end
    if flags == 0xF or flags == 15 then return lib.ImDrawFlags_RoundCornersAll or 0xF0 end
    return out ~= 0 and out or flags
end

