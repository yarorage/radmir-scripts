do
    local font_scales = {}
    local function font_id(self)
        return tonumber(ffi.cast('uintptr_t', self))
    end
    local methods = ImFont
    function ImFont.__index(self, key)
        if key == 'Scale' then
            return font_scales[font_id(self)] or 1.0
        end
        return methods[key]
    end
    function ImFont.__newindex(self, key, val)
        if key == 'Scale' then
            font_scales[font_id(self)] = tonumber(val) or 1.0
            return
        end
        error("cannot write to ImFont." .. tostring(key), 2)
    end
