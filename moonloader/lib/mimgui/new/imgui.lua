local function _is_cstr_array(v)
    if type(v) ~= 'cdata' then return false end
    if ffi.istype('const char* const[]', v) or ffi.istype('const char*[]', v) then return true end
    local s = tostring(ffi.typeof(v))
    if not s:find('char', 1, true) or not s:find('*', 1, true) or not s:find('[', 1, true) then
        return false
    end
    if s:find('(*)', 1, true) then return false end
    return true
end
local function _as_cstr_arr(v)
    return ffi.cast('const char* const*', v)
end
local function _table_to_cstr_arr(t, n)
    n = n or #t
    local arr = ffi.new('const char*[?]', n)
    for i = 0, n - 1 do
        local s = t[i + 1]
        if s == nil then s = t[i] end
        arr[i] = s
    end
    return arr, n
end
