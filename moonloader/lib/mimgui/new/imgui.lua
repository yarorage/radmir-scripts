function M.TextureRefFrom(tex)
    if tex == nil then
        return ffi.new('ImTextureRef')
    end
    if _is_tex_ref(tex) then
        if ffi.istype('ImTextureRef', tex) then
            return tex
        end
        return tex[0]
    end
    local tex_id = type(tex) == 'number'
        and ffi.cast('ImTextureID', tex)
        or  ffi.cast('ImTextureID', ffi.cast('intptr_t', tex))
    local ref = ffi.new('ImTextureRef')
    ref._TexData = nil
    ref._TexID = tex_id
    return ref
end

